const { buildSync } = require("esbuild");
const { readFileSync, writeFileSync, mkdirSync } = require("node:fs");
const { join } = require("node:path");
const root = join(__dirname, "..");
const result = buildSync({
  entryPoints: [join(root, "formatter-core.cjs")], bundle: true, write: false,
  platform: "browser", format: "iife", globalName: "WorkflowFormatter",
  target: ["es2022"], minify: true, legalComments: "eof",
  banner: { js: "// Generated by npm run build:formatter. Includes yaml 2.9.1 (ISC); see vendor/yaml-LICENSE." }
});
const artifacts = [
  [join(root, "vendor", "formatter.bundle.js"), result.outputFiles[0].text],
  [join(root, "vendor", "yaml-LICENSE"), readFileSync(join(root, "node_modules", "yaml", "LICENSE"), "utf8")]
];
mkdirSync(join(root, "vendor"), { recursive: true });
for (const [path, text] of artifacts) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== text.replace(/\r\n/g, "\n")) {
      throw new Error(`${path} is stale. Run npm run build:formatter and commit the generated artifact.`);
    }
  } else writeFileSync(path, text);
}
console.log(process.argv.includes("--check") ? "Formatter bundle is reproducible and current." : "Built local formatter bundle and YAML license.");
